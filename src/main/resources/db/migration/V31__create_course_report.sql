-- 코스 신고(스펙 025, 이슈 #87). 직접 신고와 '별로에요' 후기에서 온 신고를 한 테이블에 모은다.
-- review_id가 있으면 그 후기에서 온 신고(후기당 1건, 후기 삭제 시 함께 삭제), 없으면 직접 신고다.
-- 기존 review_course_issue 데이터 이관·삭제는 V32에서 한다(Review 매핑을 옮기는 커밋과 맞춘다).
CREATE TABLE course_report (
    id          BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT    NOT NULL REFERENCES course (place_id) ON DELETE CASCADE,
    reporter_id BIGINT    NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    review_id   BIGINT    REFERENCES review (id) ON DELETE CASCADE,
    -- 기타 직접 입력. 길이는 grapheme 기준(스펙 018)이라 컬럼 폭이 아니라 애플리케이션이 강제한다.
    detail      TEXT,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL,
    CONSTRAINT uq_course_report_review UNIQUE (review_id)
);

-- 직접 신고는 같은 회원·같은 코스에 1건(중복 신고 멱등). 후기에서 온 신고는 후기마다 생기므로 제외한다.
CREATE UNIQUE INDEX uq_course_report_direct
    ON course_report (course_id, reporter_id)
    WHERE review_id IS NULL;

-- 문제 항목(복수 선택). 값 목록은 Java enum(CourseIssue)과 정확히 일치해야 한다.
CREATE TABLE course_report_issue (
    course_report_id BIGINT      NOT NULL REFERENCES course_report (id) ON DELETE CASCADE,
    issue            VARCHAR(30) NOT NULL,
    PRIMARY KEY (course_report_id, issue),
    CONSTRAINT ck_course_report_issue_issue
        CHECK (issue IN ('VEHICLE_RESTRICTED', 'ROAD_INFO_MISMATCH', 'CONSTRUCTION',
                         'NOT_FOR_PRACTICE', 'OTHER'))
);
